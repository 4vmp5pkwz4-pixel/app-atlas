const {test,expect}=require('@playwright/test');
const root='/apps/brahmi/';
test('complete pronunciation registry, exact contrasts, regional signs and matrix',async({page})=>{
 await page.goto(root+'pronunciation.html#11013');
 await page.locator('#lang').selectOption('en');
 await expect(page.locator('#count')).toHaveText('115 / 115');
 await expect(page.locator('.sign')).toHaveCount(115);
 await expect(page.locator('#ipa')).toHaveText('[k]');
 await expect(page.locator('#chords')).toContainText('KeyK');
 await page.locator('#search').fill('U+11014');
 await expect(page.locator('.sign')).toHaveCount(1);
 await page.locator('.sign').click();
 await expect(page.locator('#ipa')).toHaveText('[kʰ]');
 await page.locator('#search').fill('U+1107F');
 await page.locator('.sign').click();
 await expect(page.locator('#ipa')).toHaveText('—');
 await expect(page.locator('#practice')).toBeDisabled();
 await expect(page.locator('#listen')).toBeDisabled();
 await expect(page.locator('#matrixRows tr')).toHaveCount(5);
 await page.locator('#search').fill('');
 await page.locator('#kind').selectOption('consonant');
 await expect(page.locator('.sign')).toHaveCount(38);
 await page.locator('#lang').selectOption('ru');
 await expect(page.locator('h1')).toHaveText('Словарь произношений');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2)).toBe(true);
});
